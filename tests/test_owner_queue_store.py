def test_answer_rules():
    d, q, m = make(), make(kind="question", question="why?", options=None), make(kind="message", question="fyi", options=None)
    for iid, bad in ((d, {"option": "Z"}), (d, {}), (q, {"option": "A"}), (m, {"option": "A"}),
                      (m, {"option": "read", "text": "x"}), (d, {"text": "t" * 4001})):
        with pytest.raises(OQ.Refused) as e:
            OQ.answer_item(iid, bad, "o@x.com")
        assert e.value.status == 422
    assert OQ.answer_item(q, {"text": "because"}, "o")["answer"]["text"] == "because"
    r = OQ.answer_item(m, {"option": "read"}, "o")
    assert r["state"] == "read" and r["answer"]["option"] == "read" and r["answer"]["text"] is None
    m2 = make(kind="message", question="fyi2", options=None)
    assert OQ.answer_item(m2, {"text": "ok, thanks"}, "o")["state"] == "answered"
    assert OQ.answer_item(d, {"option": "A"}, "o")["state"] == "answered"
    with pytest.raises(OQ.Refused) as e:
        OQ.answer_item(d, {"option": "B"}, "o")
    assert e.value.status == 409
    with pytest.raises(OQ.Refused) as e:
        OQ.answer_item("oq-000000000000", {"text": "x"}, "o")
    assert e.value.status == 404


