def test_queue_order_is_pure_band_then_oldest():
    items = [{"id": "m1", "kind": "message", "created_at": "2026-11-01T00:00:00Z"},
             {"id": "d2", "kind": "decision", "created_at": "2026-11-03T00:00:00Z"},
             {"id": "q1", "kind": "question", "created_at": "2026-11-02T00:00:00Z"},
             {"id": "c1", "kind": "catalog_write", "created_at": "2026-11-04T00:00:00Z"},
             {"id": "m0", "kind": "message", "created_at": "2026-10-30T00:00:00Z"}]
    assert [i["id"] for i in OQ.queue_order(items)] == ["q1", "d2", "c1", "m0", "m1"]
    assert [i["id"] for i in items][0] == "m1"          # the input is not mutated


def test_idempotent_repeat_and_flood_cap():
    a = OQ.create_item("t1", body())
    b = OQ.create_item("t1", body())
    assert a["id"] == b["id"] and a["created"] and not b["created"]
    assert OQ.create_item("t2", body())["id"] != a["id"]                       # another token: its own item
    assert OQ.create_item("t1", body(asked_by="other"))["id"] != a["id"]       # another session
    for i in range(OQ.MAX_OPEN_PER_TOKEN - 2):
        OQ.create_item("t1", body(question=f"q{i}"))
    with pytest.raises(OQ.Refused) as e:
        OQ.create_item("t1", body(question="one too many"))
    assert e.value.status == 429
    OQ.withdraw_item("t1", a["id"])
    OQ.create_item("t1", body(question="fits now"))
    # after the answer, the same question may be asked again
    c = OQ.create_item("t2", body())
    OQ.answer_item(c["id"], {"option": "A"}, "o@x.com")
    assert OQ.create_item("t2", body())["id"] != c["id"]


