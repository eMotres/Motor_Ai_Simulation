VEC_OUT = ("outside_message", "Hello Zoë, | a | b |", "p@example.test", "f995a1707dab63afe05c785ba308c78b8873c55708ebcf4b392805c25b86ca11")
VEC_CAT = ("catalog_write", "| old | new |", None, "f412c5546d97352f72093510ebe8552b0e6c96f6e424c0fba2127a2c6d1b3bb6")


def test_shared_hash_vector():
    for k, d, r, h in (VEC_OUT, VEC_CAT):
        assert OQ.approval_hash(k, d, r) == h
    assert OQ.approval_hash("catalog_write", "x", "") == OQ.approval_hash("catalog_write", "x", None)


def appr(kind="outside_message", **kw):
    b = {"kind": kind, "asked_by": "US · pump", "question": "Send it?", "detail": "Final text", "recipient": "p@example.test"}
    if kind == "catalog_write":
        b.pop("recipient")
    b.update(kw)
    return b


def test_approval_kinds_422_cases_and_fixed_options():
    for bad in (appr(detail=None), appr(detail="  "), appr(recipient=None), appr(recipient=""), appr(recipient="r" * 501),
                appr(options=[{"label": "A"}, {"label": "B"}]), appr("catalog_write", detail=None),
                appr("catalog_write", options=[{"label": "A"}, {"label": "B"}]), appr("catalog_write", recipient="x@y.z")):
        with pytest.raises(OQ.Refused) as e:
            OQ.create_item("t1", bad)
        assert e.value.status == 422, bad
    iid = OQ.create_item("t1", appr())["id"]
    it = OQ.get_item(iid)
    assert [o["label"] for o in it["options"]] == ["Approve", "Reject"] and it["recipient"] == "p@example.test"
    assert OQ.get_item(OQ.create_item("t1", appr("catalog_write", question="Write it?"))["id"])["recipient"] is None
    assert OQ.create_item("t1", appr(options=[]))["created"] is False                      # an empty list is "none sent"


def test_approval_hash_stored_for_approve_and_reject_and_changes_with_content():
    a = OQ.create_item("t1", appr())["id"]
    b = OQ.create_item("t1", appr(question="Send the other?", detail="Final text 2"))["id"]
    c = OQ.create_item("t1", appr("catalog_write", question="Write?", detail="| old | new |"))["id"]
    ra = OQ.answer_item(a, {"option": "Approve", "text": "but mind the tone"}, "o@x.com")
    rb = OQ.answer_item(b, {"option": "Reject"}, "o@x.com")
    rc = OQ.answer_item(c, {"option": "Approve"}, "o@x.com")
    assert ra["answer"]["text"] == "but mind the tone" and ra["answer"]["option"] == "Approve"
    assert ra["answer"]["approved_hash"] == OQ.approval_hash("outside_message", "Final text", "p@example.test")
    assert rb["answer"]["approved_hash"] == OQ.approval_hash("outside_message", "Final text 2", "p@example.test")
    assert ra["answer"]["approved_hash"] != rb["answer"]["approved_hash"]
    assert rc["answer"]["approved_hash"] == VEC_CAT[3]
    assert OQ.get_item(a)["answer"]["approved_hash"] == ra["answer"]["approved_hash"]
    d = OQ.create_item("t1", appr(question="third", recipient="other@example.test"))["id"]
    assert OQ.answer_item(d, {"option": "Approve"}, "o")["answer"]["approved_hash"] != ra["answer"]["approved_hash"]
    e = OQ.create_item("t1", appr(question="fourth"))["id"]
    with pytest.raises(OQ.Refused) as ex:
        OQ.answer_item(e, {"text": "just text"}, "o")
    assert ex.value.status == 422
    with pytest.raises(OQ.Refused):
        OQ.answer_item(e, {"option": "Maybe"}, "o")
    # a plain decision carries no hash
    dd = OQ.create_item("t1", body(question="plain"))["id"]
    assert "approved_hash" not in OQ.answer_item(dd, {"option": "A"}, "o")["answer"]


