def body(**kw):
    b = {"kind": "decision", "asked_by": "US · pump", "question": "Which winding?",
         "options": [{"label": "A", "recommended": True}, {"label": "B"}]}
    b.update(kw)
    return b


def make(name="t1", **kw):
    return OQ.create_item(name, body(**kw))["id"]


def test_validation_rejects_never_truncates():
    for bad in (body(kind="x"), body(question="x" * 301), body(question=""), body(detail="d" * 4001),
                body(blocks="b" * 201), body(asked_by="s" * 81), body(options=[{"label": "A"}]),
                body(options=[{"label": str(i)} for i in range(6)]),
                body(options=[{"label": "A", "recommended": True}, {"label": "B", "recommended": True}]),
                body(options=[{"label": "A" * 41}, {"label": "B"}]),
                body(options=[{"label": "A"}, {"label": "A"}]),
                body(kind="message", options=[{"label": "A"}, {"label": "B"}]),
                body(question="two\nlines")):
        with pytest.raises(OQ.Refused) as e:
            OQ.create_item("t1", bad)
        assert e.value.status == 422
    assert OQ.list_items() == []
    ok = OQ.create_item("t1", body(kind="question", options=None))
    assert ok["created"]


