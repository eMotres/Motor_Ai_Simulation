"""ReportLab renderer for the production process document.

The HTML generated by ``process_steps.document_html`` remains the source of
numbering and text.  This module interprets its deliberately small element set
as ReportLab flowables and embeds the authorized raster images supplied by the
route layer.
"""
from __future__ import annotations

import html
import logging
import math
import os
import re
import tempfile
import threading
import warnings
from html.parser import HTMLParser
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

log = logging.getLogger(__name__)

MAX_IMAGE_COUNT = 200
MAX_IMAGE_SOURCE_BYTES = 256 * 1024 * 1024
# A decoded source image can require several bytes per pixel during color
# conversion.  Keep each source modest and bound the sum of thumbnail pixels
# that ReportLab may retain while it builds the document.
MAX_IMAGE_PIXELS = 16_000_000
MAX_PREPARED_IMAGE_PIXELS = 20_000_000
MAX_HTML_BYTES = 1 * 1024 * 1024
MAX_RENDER_IMAGES = 40
MAX_RENDER_CONCURRENCY = 2
MAX_HTML_ELEMENTS = 20_000
_FONT_NAME = "ProductionCJK"
_FONT_LOCK = threading.Lock()
_FONT_READY = False
_RENDER_SEMAPHORE = threading.BoundedSemaphore(MAX_RENDER_CONCURRENCY)


class ProcessPdfUnavailable(RuntimeError):
    """ReportLab, Pillow, or an embeddable CJK TrueType font is unavailable."""


class ProcessPdfLimitError(RuntimeError):
    """The authorized process images exceed renderer limits."""


class ProcessPdfRenderError(RuntimeError):
    """A real PDF or image rendering failure; callers must not silently fallback."""


def _font_candidates() -> list[Path]:
    out: list[Path] = []
    override = (os.environ.get("MOTRES_PRODUCTION_CJK_FONT") or "").strip()
    if override:
        out.append(Path(override))
    out.extend((
        Path("/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc"),
        Path(r"C:\Windows\Fonts\simsun.ttc"),
        Path(r"C:\Windows\Fonts\msyh.ttc"),
    ))
    return out


def _register_cjk_font() -> str:
    global _FONT_READY
    with _FONT_LOCK:
        if _FONT_READY:
            return _FONT_NAME
        try:
            from reportlab.pdfbase import pdfmetrics
            from reportlab.pdfbase.ttfonts import TTFont
        except ImportError as exc:
            raise ProcessPdfUnavailable("ReportLab is not installed") from exc
        failures = []
        for font_path in _font_candidates():
            if not font_path.is_file():
                continue
            try:
                pdfmetrics.registerFont(TTFont(_FONT_NAME, str(font_path), subfontIndex=0, validate=0))
                # The selected TrueType face is embedded in every generated PDF.
                pdfmetrics.registerFontFamily(_FONT_NAME, normal=_FONT_NAME, bold=_FONT_NAME,
                                              italic=_FONT_NAME, boldItalic=_FONT_NAME)
                _FONT_READY = True
                return _FONT_NAME
            except Exception as exc:  # malformed/unreadable candidate; try the next known font
                failures.append("%s: %s" % (font_path, exc))
        detail = "; ".join(failures[-2:])
        raise ProcessPdfUnavailable("No embeddable CJK TrueType font is available" + (": " + detail if detail else ""))


def _styles(font_name: str):
    from reportlab.lib import colors
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.enums import TA_LEFT

    body = ParagraphStyle("ProcessBody", fontName=font_name, fontSize=9.5, leading=14,
                          textColor=colors.HexColor("#202124"), spaceAfter=5, wordWrap="CJK",
                          splitLongWords=1, alignment=TA_LEFT)
    return {
        "h1": ParagraphStyle("ProcessH1", parent=body, fontSize=18, leading=23, spaceAfter=4),
        "h2": ParagraphStyle("ProcessH2", parent=body, fontSize=13, leading=17, spaceBefore=12, spaceAfter=5,
                             keepWithNext=True, textColor=colors.HexColor("#1f4e79")),
        "h3": ParagraphStyle("ProcessH3", parent=body, fontSize=10.5, leading=14, spaceBefore=7, spaceAfter=3,
                             keepWithNext=True),
        "p": body,
        "li": ParagraphStyle("ProcessLi", parent=body, leftIndent=14, firstLineIndent=-10, spaceAfter=2),
        "cell": ParagraphStyle("ProcessCell", parent=body, fontSize=8, leading=10, spaceAfter=0),
    }


class _ProcessHtmlParser(HTMLParser):
    """Translate the renderer's limited HTML vocabulary into ReportLab flowables."""

    _BLOCKS = {"h1", "h2", "h3", "p", "li"}
    _INLINE = {"b", "strong", "i", "em", "u", "sub", "sup"}

    def __init__(self, styles: dict, step_images: dict[int, list[dict]], max_width: float,
                 max_height: float, lang: str):
        super().__init__(convert_charrefs=True)
        self.styles = styles
        self.step_images = step_images
        self.max_width = max_width
        self.max_height = max_height
        self.lang = lang
        self.story: list[Any] = []
        self.capture: str | None = None
        self.fragments: list[str] = []
        self.rows: list[list[Any]] = []
        self.row: list[Any] | None = None
        self.in_table = False
        self.step_number: int | None = None
        self.element_count = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.element_count += 1
        if self.element_count > MAX_HTML_ELEMENTS:
            raise ProcessPdfLimitError("The process document exceeds the PDF element limit.")
        attrs_d = dict(attrs)
        if tag in self._BLOCKS:
            self.capture = tag
            self.fragments = []
            if tag == "h2":
                match = re.fullmatch(r"step-(\d+)", str(attrs_d.get("id") or ""))
                self.step_number = int(match.group(1)) if match else None
        elif tag == "table":
            self.in_table = True
            self.rows = []
        elif tag == "tr":
            self.row = []
        elif tag in ("td", "th"):
            self.capture = "cell"
            self.fragments = []
        elif tag in self._INLINE and self.capture:
            self.fragments.append("<%s>" % ("b" if tag == "strong" else "i" if tag == "em" else tag))
        elif tag == "br" and self.capture:
            self.fragments.append("<br/>")

    def handle_endtag(self, tag: str) -> None:
        if tag in self._INLINE and self.capture:
            self.fragments.append("</%s>" % ("b" if tag == "strong" else "i" if tag == "em" else tag))
        elif tag in ("td", "th") and self.capture == "cell":
            from reportlab.platypus import Paragraph
            if self.row is not None:
                self.row.append(Paragraph("".join(self.fragments), self.styles["cell"]))
            self.capture = None
            self.fragments = []
        elif tag == "tr" and self.row is not None:
            self.rows.append(self.row)
            self.row = None
        elif tag == "table" and self.in_table:
            self._add_table()
            self.in_table = False
        elif tag in self._BLOCKS and self.capture == tag:
            self._add_block(tag, "".join(self.fragments))
            self.capture = None
            self.fragments = []

    def handle_data(self, data: str) -> None:
        if self.capture:
            self.fragments.append(escape(data))

    def _add_block(self, tag: str, text: str) -> None:
        from reportlab.platypus import Paragraph, Spacer, Image

        value = text.strip()
        if value:
            self.story.append(Paragraph(value, self.styles[tag]))
        if tag == "h2" and self.step_number is not None:
            for image in self.step_images.get(self.step_number, []):
                self.story.append(Image(str(image["path"]), width=self.max_width,
                                        height=self.max_height, kind="bound", hAlign="LEFT"))
                if image.get("name"):
                    self.story.append(Paragraph(escape(str(image["name"])), self.styles["cell"]))
                self.story.append(Spacer(1, 4))

    def _add_table(self) -> None:
        if not self.rows:
            return
        from reportlab.lib import colors
        from reportlab.platypus import Paragraph, Table, TableStyle, Spacer

        column_count = max(len(row) for row in self.rows)
        rows = [row + [Paragraph("", self.styles["cell"])] * (column_count - len(row))
                for row in self.rows]
        column_width = self.max_width / column_count
        table = Table(rows, colWidths=[column_width] * column_count, repeatRows=1,
                      hAlign="LEFT", splitByRow=1, splitInRow=1)
        table.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#b7bec7")),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f6")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        self.story.extend((table, Spacer(1, 5)))


def _prepare_images(step_images: dict[int, list[dict]], temp_dir: str) -> dict[int, list[dict]]:
    if not step_images:
        return {}
    try:
        from PIL import Image as PILImage, ImageOps
    except ImportError as exc:
        raise ProcessPdfUnavailable("Pillow is required to embed process images") from exc

    image_count = sum(len(items) for items in step_images.values())
    source_bytes = sum(Path(item["path"]).stat().st_size for items in step_images.values() for item in items)
    image_limit = min(MAX_IMAGE_COUNT, MAX_RENDER_IMAGES)
    if image_count > image_limit or source_bytes > MAX_IMAGE_SOURCE_BYTES:
        raise ProcessPdfLimitError("Process images exceed the PDF limit (%d images, %d MiB)." %
                                   (image_limit, MAX_IMAGE_SOURCE_BYTES // (1024 * 1024)))
    out: dict[int, list[dict]] = {}
    prepared_pixels = 0
    for step_num, images in step_images.items():
        prepared = []
        for index, item in enumerate(images):
            source = Path(item["path"])
            try:
                with warnings.catch_warnings():
                    warnings.simplefilter("error", PILImage.DecompressionBombWarning)
                    with PILImage.open(source) as original:
                        if original.width * original.height > MAX_IMAGE_PIXELS:
                            raise ProcessPdfLimitError("A process image exceeds the 16 megapixel limit.")
                        # draft can reduce JPEG decode size. thumbnail mutates in
                        # place, so no full-resolution copy exists before resize.
                        orientation = original.getexif().get(274)
                        thumb_size = (1200, 1600) if orientation in (5, 6, 7, 8) else (1600, 1200)
                        display_width, display_height = original.size
                        if orientation in (5, 6, 7, 8):
                            display_width, display_height = display_height, display_width
                        scale = min(1.0, 1600 / display_width, 1200 / display_height)
                        prepared_pixels += math.ceil(display_width * scale) * math.ceil(display_height * scale)
                        if prepared_pixels > MAX_PREPARED_IMAGE_PIXELS:
                            raise ProcessPdfLimitError("Process image thumbnails exceed the 20 megapixel workload limit.")
                        original.draft("RGB", thumb_size)
                        original.thumbnail(thumb_size, PILImage.Resampling.LANCZOS)
                        image = ImageOps.exif_transpose(original)
                        try:
                            if image.mode not in ("RGB", "RGBA"):
                                converted = image.convert("RGBA" if "transparency" in image.info else "RGB")
                                image.close()
                                image = converted
                            if image.mode == "RGBA":
                                background = PILImage.new("RGB", image.size, "white")
                                alpha = image.getchannel("A")
                                try:
                                    background.paste(image, mask=alpha)
                                finally:
                                    alpha.close()
                                image.close()
                                image = background
                            target = Path(temp_dir) / ("process-image-%d-%d.jpg" % (step_num, index))
                            image.save(target, format="JPEG", quality=88, optimize=False)
                        finally:
                            image.close()
            except ProcessPdfLimitError:
                raise
            except Exception as exc:  # malformed or unreadable image is a real render error
                raise ProcessPdfRenderError("Could not render process image %s" % item.get("name", source.name)) from exc
            prepared.append({"path": target, "name": item.get("name")})
        out[step_num] = prepared
    return out


def render_process_pdf(html_document: str, output_path: str | Path, *,
                       step_images: dict[int, list[dict]] | None = None, lang: str = "en") -> None:
    """Render the exact process HTML structure to an A4 PDF with embedded CJK font."""
    if len(html_document.encode("utf-8")) > MAX_HTML_BYTES:
        raise ProcessPdfLimitError("The process document exceeds the 1 MiB PDF input limit.")
    # This synchronous renderer runs in API worker threads. Admission is
    # bounded so image decode and ReportLab's in-memory PDF buffer cannot
    # multiply without limit under concurrent downloads.
    with _RENDER_SEMAPHORE:
        _render_process_pdf_locked(html_document, output_path, step_images=step_images, lang=lang)


def _render_process_pdf_locked(html_document: str, output_path: str | Path, *,
                               step_images: dict[int, list[dict]] | None = None, lang: str = "en") -> None:
    font_name = _register_cjk_font()
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.units import mm
        from reportlab.platypus import SimpleDocTemplate, Spacer, Paragraph
    except ImportError as exc:
        raise ProcessPdfUnavailable("ReportLab is not installed") from exc
    from reportlab.lib import colors
    from reportlab.lib.styles import ParagraphStyle

    output = Path(output_path)
    with tempfile.TemporaryDirectory(prefix="production-process-pdf-") as temp_dir:
        images = _prepare_images(step_images or {}, temp_dir)
        width, _height = A4
        doc = SimpleDocTemplate(str(output), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                                topMargin=17 * mm, bottomMargin=18 * mm, title="Production process")
        styles = _styles(font_name)
        # SimpleDocTemplate's default frame has 6 pt padding on each side.
        parser = _ProcessHtmlParser(styles, images, width - 36 * mm - 12, 220 * mm, lang)
        try:
            parser.feed(html_document)
            parser.close()
            story = parser.story or [Paragraph(html.escape("No process content."), styles["p"]), Spacer(1, 1)]

            def footer(canvas, document):
                canvas.saveState()
                canvas.setFont(font_name, 8)
                canvas.setFillColor(colors.HexColor("#667085"))
                page_label = ("第 %d 页" % document.page) if lang == "zh" else ("Page %d" % document.page)
                canvas.drawRightString(width - 18 * mm, 9 * mm, page_label)
                canvas.restoreState()

            doc.build(story, onFirstPage=footer, onLaterPages=footer)
        except (ProcessPdfRenderError, ProcessPdfLimitError):
            raise
        except Exception as exc:
            log.exception("production process PDF rendering failed")
            raise ProcessPdfRenderError("The process PDF could not be rendered") from exc
