def test_tokens_hashed_once_unique_revocable(tmp_path):
    tok = OQ.create_token("agent-a", "o@x.com")
    assert tok.startswith("oq_") and len(tok) == 43
    raw = (tmp_path / "oq" / "tokens.json").read_text()
    assert tok not in raw and "token_hash" in raw
    assert OQ.verify_token("Bearer " + tok) == "agent-a"
    assert OQ.verify_token("bearer " + tok) == "agent-a"
    wrong_last = "Bearer " + tok[:-1] + ("y" if tok[-1] == "x" else "x")
    for bad in (None, "", tok, "Bearer", "Bearer oq_nope", wrong_last, "Basic " + tok, "Bearer mcnode_" + tok[3:]):
        assert OQ.verify_token(bad) is None
    with pytest.raises(OQ.Refused) as e:
        OQ.create_token("agent-a", "o@x.com")
    assert e.value.status == 409
    for bad in ("", "a b", "x" * 41, None):
        with pytest.raises(OQ.Refused):
            OQ.create_token(bad, "o")
    listed = OQ.list_tokens()
    assert [t["name"] for t in listed] == ["agent-a"] and "token_hash" not in listed[0]
    assert OQ.revoke_token("agent-a") and OQ.verify_token("Bearer " + tok) is None
    assert not OQ.revoke_token("nobody")
    with pytest.raises(OQ.Refused):
        OQ.create_token("agent-a", "o")                  # a revoked name stays taken
    assert (tmp_path / "oq" / "tokens.json").stat().st_mode & 0o077 == 0


def test_damaged_files_fail_closed_and_are_not_reset(tmp_path):
    make()
    p = tmp_path / "oq" / "items.jsonl"
    good = p.read_text()
    p.write_text(good + "{not json\n")
    for fn in (lambda: OQ.list_items(), lambda: OQ.create_item("t1", body(question="new")), lambda: OQ.counts()):
        with pytest.raises(OQ.StoreDamaged):
            fn()
    assert p.read_text() == good + "{not json\n"          # untouched
    tp = tmp_path / "oq" / "tokens.json"
    tp.write_text("[broken")
    with pytest.raises(OQ.StoreDamaged):
        OQ.verify_token("Bearer oq_x")
    with pytest.raises(OQ.StoreDamaged):
        OQ.create_token("n", "o")
    assert tp.read_text() == "[broken"


